export function formatAnswer(value) {
  return Math.abs(value) >= 1e5 ||
    (Math.abs(value) > 0 && Math.abs(value) < 0.001)
    ? value.toExponential(4)
    : Number(value.toPrecision(5)).toString();
}
/** Accept a number or scientific notation, never evaluate user input as code. */
export function parseNumericAnswer(raw) {
  const v = String(raw)
    .trim()
    .replaceAll("−", "-")
    .replace(/\s+/g, "")
    .replace(/[×x*]10\^?/i, "e");
  return /^[+-]?(?:\d+(?:\.\d*)?|\.\d+)(?:e[+-]?\d+)?$/i.test(v) &&
    Number.isFinite(Number(v))
    ? Number(v)
    : null;
}
export function checkNumericAnswer(question, raw) {
  const value = parseNumericAnswer(raw);
  if (value === null) return { valid: false, correct: false };
  const tolerance =
    question.answer === 0 ? 1e-12 : Math.abs(question.answer) * 0.02;
  return {
    valid: true,
    correct: Math.abs(value - question.answer) <= tolerance,
    value,
  };
}
